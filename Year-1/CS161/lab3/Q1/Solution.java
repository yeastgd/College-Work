
public class Solution {
    public static void main(String[] args) {
        int i = 10;
        while (i <= 20) {
            System.out.print(i + " ");
            i++;
        }
    
        System.out.println(); // new line

        for (int j = 20; j >= 10; j--) {
            System.out.print(j + " ");
        }
    }
}
